FENCE = re.compile(r"^(```+|~~~+).*?^\1", re.M | re.S)
CODESPAN = re.compile(r"(`+)(?!`)(.+?)(?<!`)\1(?!`)", re.S)


def dj_files():
    return sorted(f for f in os.listdir(os.path.join(SRC, "docs"))
                  if f.endswith(".dj"))


def extract_doctests():
    """`FILTER --> EXPECTED` code spans, the way docs/tests.jq reads them."""
    items = []
    for name in dj_files():
        path = os.path.join(SRC, "docs", name)
        text = open(path, encoding="utf-8").read()
        # Fenced blocks are prose/XML/shell, never doc tests; dropping them
        # also removes the one `<!-- ... -->` XML comment in formats.dj.
        body = FENCE.sub(lambda m: "\n" * m.group(0).count("\n"), text)
        for m in CODESPAN.finditer(body):
            span = m.group(2)
            if "-->" not in span:
                continue
            line = body.count("\n", 0, m.start()) + 1
            filt = span.split("-->")[0]
            filt = re.sub(r"#[^\n]*", "", filt)      # docs/tests.jq
            filt = " ".join(filt.split())
            if not filt:
                SKIPPED["doctest:empty-filter"] += 1
                continue
            items.append(dict(
                source="doctest", origin=f"docs/{name}:{line}",
                argv=[filt], stdin="null\n", cwd="targets/jaq/src",
                description=f"manual doc test: {filt[:60]}"))
    return items


PRODUCERS = {"echo": "/usr/bin/echo", "printf": "/usr/bin/printf",
             "seq": "/usr/bin/seq"}


def extract_doccli():
    """`$ producer | jaq ARGS` lines, the way docs/cli-tests.jq reads them."""
    items = []
    for name in dj_files():
        path = os.path.join(SRC, "docs", name)
        lines = open(path, encoding="utf-8").read().split("\n")
        for i, raw in enumerate(lines, 1):
            if not raw.startswith("$ "):
                continue
            cmd = raw[2:]
            j = i
            while cmd.endswith("\\"):                # shelltest.rs continuation
                cmd = cmd[:-1] + lines[j]
                j += 1
            try:
                lx = shlex.shlex(cmd, posix=True, punctuation_chars=True)
                lx.whitespace_split = True
                toks = list(lx)
            except ValueError:
                SKIPPED["doccli:unparsable"] += 1
                continue
            if any(t in (";", "&&", "||", ">", ">>", "<", "&") for t in toks):
                SKIPPED["doccli:shell-control"] += 1   # writes files, $?, ...
                continue
            stages, cur = [], []
            for t in toks:
                if t == "|":
                    stages.append(cur)
                    cur = []
                else:
                    cur.append(t)
            stages.append(cur)
            stages = [s for s in stages if s]
            if not stages or stages[-1][0] != "jaq":
                SKIPPED["doccli:not-jaq-last"] += 1
                continue
            if len(stages) == 1:
                argv, stdin = stages[0][1:], ""
                if "-n" not in "".join(argv) and not any(
                        a.endswith(".json") or a.endswith(".xhtml")
                        for a in argv):
                    SKIPPED["doccli:would-block-on-stdin"] += 1
                    continue
            elif len(stages) == 2 and stages[0][0] in PRODUCERS:
                prod = [PRODUCERS[stages[0][0]]] + stages[0][1:]
                try:
                    out = subprocess.run(prod, capture_output=True, timeout=5)
                except (OSError, subprocess.TimeoutExpired):
                    SKIPPED["doccli:producer-failed"] += 1
                    continue
                stdin = out.stdout.decode("utf-8", "surrogateescape")
                argv = stages[-1][1:]
            else:
                SKIPPED["doccli:multi-stage"] += 1     # jaq | jaq, yes | ...
                continue
            items.append(dict(
                source="doccli", origin=f"docs/{name}:{i}",
                argv=argv, stdin=stdin, cwd="targets/jaq/src",
                description=f"manual CLI example: {cmd[:70]}"))
    return items


TEST_FILES = [
    "jaq-core/tests/tests.rs", "jaq-core/tests/defs.rs",
    "jaq-core/tests/funs.rs", "jaq-core/tests/path.rs",
    "jaq-std/tests/defs.rs", "jaq-std/tests/funs.rs",
    "jaq-json/tests/defs.rs", "jaq-json/tests/funs.rs",
    "jaq-fmts/tests/formats.rs", "jaq-fmts/tests/funs.rs",
]

CALL = re.compile(r"\b(give|gives|fail)\s*\(")
YIELDS = re.compile(r"\byields!\s*\(")


def extract_rust_tests():
    """give(input, filter, out) / gives / fail / yields!(name, filter, out)."""
    items = []
    for f in TEST_FILES:
        path = os.path.join(SRC, f)
        text = open(path, encoding="utf-8").read()
        for m in CALL.finditer(text):
            try:
                inner, _ = balanced(text, m.end() - 1)
            except (ValueError, IndexError):
                SKIPPED["test:unbalanced"] += 1
                continue
            args = split_args(inner)
            if len(args) < 2:
                SKIPPED["test:too-few-args"] += 1
                continue
            inp, filt = json_arg(args[0]), filter_arg(args[1])
            if inp is None:
                SKIPPED["test:input-not-literal"] += 1
                continue
            if filt is None:
                SKIPPED["test:filter-not-literal"] += 1
                continue
            line = text.count("\n", 0, m.start()) + 1
            items.append(dict(
                source="test", origin=f"{f}:{line}",
                argv=[" ".join(filt.split())], stdin=inp + "\n",
                cwd="targets/jaq/src",
                description=f"{m.group(1)}(): {filt[:60]}"))
        for m in YIELDS.finditer(text):
            try:
                inner, _ = balanced(text, m.end() - 1)
            except (ValueError, IndexError):
                SKIPPED["test:unbalanced"] += 1
                continue
            args = split_args(inner)
            if len(args) < 2:
                SKIPPED["test:too-few-args"] += 1
                continue
            filt = filter_arg(args[1])
            if filt is None:
                SKIPPED["test:filter-not-literal"] += 1
                continue
            line = text.count("\n", 0, m.start()) + 1
            items.append(dict(
                source="test", origin=f"{f}:{line}",
                argv=[" ".join(filt.split())], stdin="null\n",
                cwd="targets/jaq/src",
                description=f"yields!(): {filt[:60]}"))
    return items


def extract_golden():
    """jaq/tests/golden.rs --- the repository's own CLI tests."""
    path = os.path.join(SRC, "jaq/tests/golden.rs")
    text = open(path, encoding="utf-8").read()
    consts = {}
    for m in re.finditer(r'const\s+(\w+)\s*:\s*&str\s*=\s*', text):
        v, _ = rust_string_at(text, m.end())
        consts[m.group(1)] = v
    items = []
    for m in re.finditer(r"\btest!\s*\(", text):
        inner, _ = balanced(text, m.end() - 1)
        args = split_args(inner)
        if len(args) < 3:
            SKIPPED["clitest:too-few-args"] += 1
            continue
        name = args[0].strip()
        arr = args[1].strip()
        if not arr.startswith("&["):
            SKIPPED["clitest:args-not-array"] += 1
            continue
        argv = []
        bad = False
        for a in split_args(balanced(arr, 1, "[", "]")[0]):
            v = filter_arg(a)
            if v is None:
                bad = True
                break
            argv.append(v)
        if bad:
            SKIPPED["clitest:arg-not-literal"] += 1
            continue
        raw = args[2].strip()
        stdin = consts.get(raw) if raw in consts else filter_arg(raw)
        if stdin is None:
            SKIPPED["clitest:input-not-literal"] += 1
            continue
        line = text.count("\n", 0, m.start()) + 1
        items.append(dict(
            source="clitest", origin=f"jaq/tests/golden.rs:{line}",
            argv=argv, stdin=stdin,
            cwd="targets/jaq/src/jaq",   # -L tests, --rawfile tests/256.bin
            description=f"golden CLI test {name}"))
    return items


def extract_bench():
    """examples/benches/*.jq x examples/benches.json, driven as bench.sh does.

    bench.sh runs `echo $n | jaq "$(cat examples/benches/$b.jq) | length"`.
    The trailing `| length` is load-bearing: without it a benchmark at
    n = 1048576 writes a million values to stdout.
    """
    items = []
    path = os.path.join(SRC, "examples/benches.json")
    for line in open(path, encoding="utf-8"):
        line = line.strip()
        if not line:
            continue
        spec = json.loads(line)
        name, n = spec["name"], spec["n"]
        jq = os.path.join(SRC, "examples/benches", name + ".jq")
        if not os.path.exists(jq):
            SKIPPED["bench:no-jq-file"] += 1
            continue
        filt = open(jq, encoding="utf-8").read().strip() + " | length"
        items.append(dict(
            source="bench", origin=f"examples/benches/{name}.jq",
            argv=[filt], stdin=f"{n}\n", cwd="targets/jaq/src",
            description=f"bench.sh benchmark {name}, n={n}"))
    # bench.sh's three hand-written benchmarks. `empty` is run 512 times by
    # bench.sh purely to time process startup; one invocation is the item.
    items.append(dict(
        source="bench", origin="bench.sh:empty",
        argv=["-n", "empty"], stdin="", cwd="targets/jaq/src",
        description="bench.sh startup benchmark `empty`"))
    items.append(dict(
        source="bench", origin="bench.sh:bf-fib",
        argv=["-sRrf", "examples/bf.jq", "examples/fib.bf"], stdin="",
        cwd="targets/jaq/src",
        description="bench.sh bf-fib: a Brainfuck interpreter in jq"))
    # bench.sh's `defs` benchmark generates 100000 `def a: 0;` lines into a
    # process substitution. The generated file is the only large *input* the
    # repository produces, and it is a program, not data.
    os.makedirs(GEN_DIR, exist_ok=True)
    defs = os.path.join(GEN_DIR, "defs100k.jq")
    if not os.path.exists(defs):
        with open(defs, "w") as fh:
            fh.write("def a: 0;\n" * 100000)
            fh.write("empty\n")
    items.append(dict(
        source="bench", origin="bench.sh:defs",
        argv=["-n", "-f", rel(defs)], stdin="", cwd=".",
        description="bench.sh defs: parse 100000 filter definitions"))
    return items


