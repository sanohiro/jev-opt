def run_item(binary, it, timeout, env):
    cwd = os.path.join(REPO, it["cwd"])
    argv = [binary] + it["argv"]
    data = it["stdin"].encode("utf-8", "surrogateescape")
    t0 = time.perf_counter()
    try:
        p = subprocess.run(argv, input=data, cwd=cwd, env=env,
                           stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
                           timeout=timeout)
        ms = (time.perf_counter() - t0) * 1000
        return {"status": "ok", "rc": p.returncode, "ms": ms,
                "out_bytes": len(p.stdout)}
    except subprocess.TimeoutExpired:
        return {"status": "timeout", "rc": None,
                "ms": (time.perf_counter() - t0) * 1000, "out_bytes": 0}
    except OSError as e:
        return {"status": f"oserror:{e.errno}", "rc": None,
                "ms": (time.perf_counter() - t0) * 1000, "out_bytes": 0}


def cmd_run(args):
    pool = load_pool()
    sel = arm_items(args.arm, pool["items"])
    binary = os.path.abspath(args.binary)
    env = dict(os.environ)
    if args.profile_file:
        # Every arm writes to its own directory. The instrumented binary's
        # baked-in path is the frozen pgo/jaq/profraw/, which must not be
        # touched, so this is never optional for that binary.
        env["LLVM_PROFILE_FILE"] = os.path.abspath(args.profile_file)
    log = []
    t0 = time.perf_counter()
    for n, it in enumerate(sel, 1):
        r = run_item(binary, it, timeout=args.timeout, env=env)
        log.append({"id": it["id"], **r})
        if args.progress and n % 100 == 0:
            print(f"  {args.arm}: {n}/{len(sel)}", file=sys.stderr, flush=True)
    wall = time.perf_counter() - t0
    bad = [r for r in log if r["status"] != "ok"]
    print(f"arm {args.arm}: {len(sel)} invocations, {wall:.1f} s wall, "
          f"{len(bad)} did not terminate normally")
    if args.log:
        with open(args.log, "w") as fh:
            json.dump({"arm": args.arm, "n": len(sel), "wall_s": wall,
                       "runs": log}, fh, indent=1)


def main():
    p = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)

    e = sub.add_parser("extract")
    e.add_argument("--binary", required=True,
                   help="a plain (non-instrumented) jaq for the dry run")
    e.add_argument("--timeout", type=float, default=5.0)
    e.add_argument("--progress", action="store_true")
    e.set_defaults(fn=cmd_extract)

    sc = sub.add_parser("scan")
    sc.add_argument("--binary", required=True,
                    help="the INSTRUMENTED jaq (-Cprofile-generate)")
    sc.add_argument("--scratch", required=True)
    sc.add_argument("--chunk", type=int, default=60)
    sc.add_argument("--timeout", type=float, default=120.0)
    sc.add_argument("--llvm-profdata", default=None)
    sc.set_defaults(fn=cmd_scan)

    s = sub.add_parser("select")
    s.add_argument("arm")
    s.add_argument("--count", action="store_true")
    s.add_argument("--sources", action="store_true")
    s.set_defaults(fn=cmd_select)

    r = sub.add_parser("run")
    r.add_argument("arm")
    r.add_argument("--binary", required=True)
    r.add_argument("--profile-file", default=None,
                   help="LLVM_PROFILE_FILE for the child processes")
    r.add_argument("--timeout", type=float, default=60.0)
    r.add_argument("--log", default=None)
    r.add_argument("--progress", action="store_true")
    r.set_defaults(fn=cmd_run)

    args = p.parse_args()
    args.fn(args)


if __name__ == "__main__":
    main()
