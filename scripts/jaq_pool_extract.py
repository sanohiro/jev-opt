def load_pool():
    return json.load(open(POOL_JSON))


def arm_items(arm, items, keep_poison=False):
    """The subset of the pool an arm trains on.

    Items flagged `poisons_profile` are excluded from every arm unless
    keep_poison is set: they write a pointer-shaped value into one of the
    instrumented binary's counters (see `scan`), which makes that one block
    hold 99.999% of the profile and moves LLVM's whole hot/cold cutoff. The
    `T_allraw` arm is `T_all` with them left in, which is what a selector
    with no such guard would really produce.
    """
    if arm == "T_allraw":
        arm, keep_poison = "T_all", True
    if not keep_poison:
        items = [i for i in items if not i.get("poisons_profile")]
    if arm == "T_all":
        return list(items)
    if arm == "T_readme":
        return [i for i in items if i["source"] in ("doctest", "doccli")]
    if arm == "T_big":
        # Top 10% by input bytes --- the naive "train on the big inputs" rule.
        s = sorted(items, key=lambda i: -i["input_bytes"])
        return s[:max(1, len(s) // 10)]
    if arm == "T_bench":
        return [i for i in items if i["source"] in ("bench", "example")]
    if arm == "T_tests":
        return [i for i in items if i["source"] in ("test", "clitest")]
    raise SystemExit(f"unknown arm {arm!r}")


