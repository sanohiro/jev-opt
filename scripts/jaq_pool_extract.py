def file_args(item):
    """Existing files named on the command line, resolved against cwd."""
    out = []
    base = os.path.join(REPO, item["cwd"])
    for a in item["argv"]:
        p = os.path.join(base, a)
        if a and not a.startswith("-") and os.path.isfile(p):
            out.append(p)
    return out


def cmd_extract(args):
    items = []
    items += extract_doctests()
    items += extract_doccli()
    items += extract_rust_tests()
    items += extract_golden()
    items += extract_bench()
    items += extract_examples()

    per = collections.Counter()
    for it in items:
        per[it["source"]] += 1
        it["id"] = f"{it['source']}-{per[it['source']]:04d}"
        nonflag = [a for a in it["argv"] if not a.startswith("-")]
        it["filter"] = max(nonflag, key=len) if nonflag else ""
        fa = file_args(it)
        it["input_paths"] = [rel(p) for p in fa]
        it["input_bytes"] = (len(it["stdin"].encode("utf-8", "surrogateescape"))
                             + sum(os.path.getsize(p) for p in fa))
        it["filter_bytes"] = len(it["filter"].encode("utf-8"))

    print(f"parsed {len(items)} candidates")
    for k, v in sorted(SKIPPED.items()):
        print(f"  skipped {k}: {v}")

    # Dry run: a candidate that cannot terminate cannot train anything. A
    # non-zero exit is kept --- fail() tests and `try ... catch` doc tests are
    # supposed to fail, and they still execute the code we care about.
    binary = os.path.abspath(args.binary)
    kept = []
    for n, it in enumerate(items, 1):
        r = run_item(binary, it, timeout=args.timeout, env=None)
        it["dry_status"] = r["status"]
        it["dry_rc"] = r["rc"]
        it["dry_ms"] = r["ms"]
        it["dry_stdout_bytes"] = r["out_bytes"]
        if r["status"] == "ok":
            kept.append(it)
        if args.progress and n % 200 == 0:
            print(f"  dry run {n}/{len(items)}", file=sys.stderr, flush=True)

    dropped = [it for it in items if it["dry_status"] != "ok"]
    print(f"dry run: {len(kept)} usable, {len(dropped)} dropped")
    bys = collections.Counter((it["source"], it["dry_status"])
                              for it in dropped)
    for (s, st), c in sorted(bys.items()):
        print(f"  dropped {s}/{st}: {c}")

    os.makedirs(POOL_DIR, exist_ok=True)
    doc = {"schema_version": 1,
           "repo_commit": subprocess.run(
               ["git", "-C", SRC, "rev-parse", "HEAD"],
               capture_output=True, text=True).stdout.strip(),
           "dry_run_binary": rel(binary),
           "dry_run_timeout_s": args.timeout,
           "parsed": len(items), "usable": len(kept),
           "skipped_at_parse": dict(SKIPPED),
           "items": kept,
           "dropped": [{k: it[k] for k in
                        ("id", "source", "origin", "dry_status", "dry_rc",
                         "description")} for it in dropped]}
    with open(POOL_JSON, "w") as fh:
        json.dump(doc, fh, indent=1)
    print(f"wrote {rel(POOL_JSON)}")
    report(kept)


def report(items):
    per = collections.Counter(it["source"] for it in items)
    print("\npool by source:")
    for s, c in sorted(per.items()):
        b = [it["input_bytes"] for it in items if it["source"] == s]
        ms = [it["dry_ms"] for it in items if it["source"] == s]
        print(f"  {s:9s} n={c:5d}  input bytes min/median/max "
              f"{min(b)}/{sorted(b)[len(b)//2]}/{max(b)}  "
              f"dry ms min/median/max "
              f"{min(ms):.0f}/{sorted(ms)[len(ms)//2]:.0f}/{max(ms):.0f}")
    b = sorted(it["input_bytes"] for it in items)
    print(f"\ninput-byte distribution over all {len(b)} items:")
    for q in (0, 10, 25, 50, 75, 90, 99, 100):
        print(f"  p{q:<3d} {b[min(len(b) - 1, q * len(b) // 100)]}")
    print(f"  total input bytes {sum(b)}")
    ms = sorted(it["dry_ms"] for it in items)
    print(f"  total dry-run wall time {sum(ms) / 1000:.1f} s, "
          f"median item {ms[len(ms) // 2]:.1f} ms")


