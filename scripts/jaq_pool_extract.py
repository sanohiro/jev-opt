# No block of jaq can be executed 1e11 times by an item that finishes in a few
# milliseconds; anything at or above this is not a count.
POISON_THRESHOLD = 10 ** 11


def _max_block(llvm_profdata, gen_bin, sub, scratch, timeout):
    raw = os.path.join(scratch, "raw")
    os.makedirs(raw, exist_ok=True)
    for f in os.listdir(raw):
        os.remove(os.path.join(raw, f))
    env = dict(os.environ)
    env["LLVM_PROFILE_FILE"] = os.path.join(raw, "%m.profraw")
    for it in sub:
        run_item(gen_bin, it, timeout=timeout, env=env)
    merged = os.path.join(scratch, "scan.profdata")
    subprocess.run([llvm_profdata, "merge", "-o", merged] +
                   [os.path.join(raw, f) for f in os.listdir(raw)], check=True)
    out = subprocess.run([llvm_profdata, "show", merged],
                         capture_output=True, text=True, check=True).stdout
    return int(re.search(r"Maximum internal block count: (\d+)", out).group(1))


def cmd_scan(args):
    """Bisect the pool for items whose profraw contains an impossible count.

    Three items in jaq v3.1.1 do: each one runs `tostring` on a big integer,
    which reaches num_bigint's `to_radix_le`, and under `-Cprofile-generate`
    that function writes a *pointer* (0x200000000000-ish, mimalloc's arena
    region) into one of its own counter slots. The value differs run to run
    in its low bits, so it is a wild write and not a count. One such block
    holds 99.999% of the merged profile's total, and `llvm-profdata show
    --detailed-summary` then puts every profile-summary percentile on that
    one block --- i.e. LLVM's hot/cold cutoff is set by garbage and the rest
    of the program is cold. Not visible in the released (uninstrumented)
    binary.
    """
    pool = load_pool()
    items = pool["items"]
    tool = args.llvm_profdata or default_llvm_profdata()
    gen = os.path.abspath(args.binary)
    scratch = args.scratch
    os.makedirs(scratch, exist_ok=True)

    def find(sub):
        if not sub or _max_block(tool, gen, sub, scratch,
                                 args.timeout) < POISON_THRESHOLD:
            return []
        if len(sub) == 1:
            return sub
        h = len(sub) // 2
        return find(sub[:h]) + find(sub[h:])

    bad = []
    for i in range(0, len(items), args.chunk):
        ch = items[i:i + args.chunk]
        m = _max_block(tool, gen, ch, scratch, args.timeout)
        print(f"chunk {i:5d}-{i + len(ch):5d} max block count {m}", flush=True)
        if m >= POISON_THRESHOLD:
            for b in find(ch):
                bad.append(b)
                print(f"   POISONS THE PROFILE: {b['id']} {b['origin']} "
                      f"| {b['filter'][:80]}", flush=True)
    ids = {b["id"] for b in bad}
    for it in items:
        it["poisons_profile"] = it["id"] in ids
    pool["poisoning_items"] = sorted(ids)
    with open(POOL_JSON, "w") as fh:
        json.dump(pool, fh, indent=1)
    print(f"\n{len(ids)} of {len(items)} pool items poison the profile; "
          f"flagged in {rel(POOL_JSON)}")


def default_llvm_profdata():
    sysroot = subprocess.run(["rustc", "--print", "sysroot"],
                             capture_output=True, text=True,
                             check=True).stdout.strip()
    triple = re.search(r"^host: (.*)$",
                       subprocess.run(["rustc", "-vV"], capture_output=True,
                                      text=True, check=True).stdout,
                       re.M).group(1)
    return f"{sysroot}/lib/rustlib/{triple}/bin/llvm-profdata"


def cmd_select(args):
    pool = load_pool()
    sel = arm_items(args.arm, pool["items"])
    if args.count:
        print(len(sel))
        return
    if args.sources:
        c = collections.Counter(i["source"] for i in sel)
        print(f"{args.arm}: n={len(sel)} "
              f"dry_wall={sum(i['dry_ms'] for i in sel) / 1000:.2f}s "
              f"input_bytes={sum(i['input_bytes'] for i in sel)} "
              + " ".join(f"{k}={v}" for k, v in sorted(c.items())))
        return
    for it in sel:
        print(it["id"])


