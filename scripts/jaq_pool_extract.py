#!/usr/bin/env python3
"""Enumerate every input inside the jaq repository that can drive the jaq CLI.

This is the candidate pool for Experiment 1 (results.md "Experiment 1 (jaq)"):
the set a `jev-opt build` selector would choose its PGO training workload
from, without the user writing a single training input. Nothing here is
generated by us --- every item comes out of `targets/jaq/src`.

Six sources, in the order a selector would plausibly discover them:

  doctest   `FILTER --> EXPECTED` code spans in docs/*.dj. This is exactly
            what the repository's own docs/tests.jq extracts and feeds to
            `jaq --run-tests`; the input is always `null`.
  doccli    `$ producer | jaq ARGS` shell examples in docs/*.dj, which
            docs/cli-tests.jq extracts and docs/shelltest.rs runs. Only the
            pipelines that reduce to exactly (producer -> jaq) are kept; the
            producer is executed here to obtain the stdin bytes, so no shell
            is involved when an arm runs.
  test      give/gives/yields!/fail calls in jaq-{core,std,json,fmts}/tests.
            These drive the *library*, not the CLI; an item is the CLI
            equivalent `jaq FILTER` with the test's input on stdin.
  clitest   test!(name, &[args], input, output) in jaq/tests/golden.rs, which
            already spawns the real binary.
  bench     examples/benches/*.jq x the `n` in examples/benches.json, driven
            exactly as bench.sh drives them (`echo $n | jaq "$(cat f.jq) |
            length"`), plus bench.sh's three hand-written benchmarks.
  example   the runnable example programs under examples/.

Subcommands:
  extract   parse everything, dry-run each candidate against a jaq binary
            with a timeout, and write targets/jaq/pool/pool.json.
  select    print the ids belonging to a named arm.
  run       run a set of ids against a binary (this is what an arm's training
            run is; scripts/pgo_train_arm.sh calls it).

Python 3 standard library only.
"""

