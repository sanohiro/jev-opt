def rust_string_at(s, i):
    """Parse the Rust string literal starting at s[i]; return (value, end)."""
    m = re.compile(r'r(#*)"').match(s, i)
    if m:
        hashes = m.group(1)
        close = '"' + hashes
        end = s.index(close, m.end())
        return s[m.end():end], end + len(close)
    if s[i] != '"':
        raise ValueError(f"not a string literal at {i}: {s[i:i+20]!r}")
    out = []
    j = i + 1
    while s[j] != '"':
        if s[j] == "\\":
            c = s[j + 1]
            out.append({"n": "\n", "t": "\t", "r": "\r", "0": "\0",
                        "\\": "\\", '"': '"', "'": "'"}.get(c, c))
            if c == "u":
                m = re.compile(r"u\{([0-9a-fA-F]+)\}").match(s, j + 1)
                out[-1] = chr(int(m.group(1), 16))
                j = m.end()
                continue
            j += 2
            continue
        out.append(s[j])
        j += 1
    return "".join(out), j + 1


def balanced(s, i, open_ch="(", close_ch=")"):
    """s[i] is open_ch; return (inner text, index just past close_ch)."""
    depth = 0
    j = i
    while True:
        c = s[j]
        if c in "\"" or (c == "r" and re.compile(r'r#*"').match(s, j)):
            try:
                _, j = rust_string_at(s, j)
                continue
            except (ValueError, IndexError):
                pass
        if c == "'" and j + 2 < len(s) and (s[j + 2] == "'" or s[j + 1] == "\\"):
            j = s.index("'", j + 1) + 1          # char literal
            continue
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
            if depth == 0:
                return s[i + 1:j], j + 1
        j += 1


def split_args(inner):
    """Split a call's argument list on top-level commas."""
    parts, depth, start, j = [], 0, 0, 0
    while j < len(inner):
        c = inner[j]
        if c == '"' or (c == "r" and re.compile(r'r#*"').match(inner, j)):
            try:
                _, j = rust_string_at(inner, j)
                continue
            except (ValueError, IndexError):
                pass
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        elif c == "," and depth == 0:
            parts.append(inner[start:j])
            start = j + 1
        j += 1
    parts.append(inner[start:])
    return [p.strip() for p in parts if p.strip()]


def json_arg(text):
    """`json!(X)` or a bare JSON-ish Rust expression -> compact JSON text."""
    text = text.strip()
    m = re.match(r"^json!\s*", text)
    if m:
        inner, _ = balanced(text, m.end())
        text = inner.strip()
    if text.startswith("r") and re.match(r'^r#*"', text):
        try:
            v, _ = rust_string_at(text, 0)
            return json.dumps(v)
        except (ValueError, IndexError):
            return None
    if text.startswith('"'):
        try:
            v, _ = rust_string_at(text, 0)
            return json.dumps(v)
        except (ValueError, IndexError):
            return None
    # json!() bodies are JSON with Rust escapes already resolved by the
    # tokenizer; everything that is not literal JSON (a Rust variable, a
    # helper call, a format string) is dropped and counted.
    try:
        return json.dumps(json.loads(text), separators=(",", ":"))
    except (ValueError, TypeError):
        return None


def filter_arg(text):
    text = text.strip()
    if text.startswith('"') or re.match(r'^r#*"', text):
        try:
            v, _ = rust_string_at(text, 0)
            return v
        except (ValueError, IndexError):
            return None
    return None


